static const char *depad_str(const char *depad_str, char depad_char) {
    while (*depad_str == depad_char)
        ++depad_str;
    return depad_str;
}

bool oled_task_kb(void) {

    static uint8_t current_layer = 0;
    static bool done_once = false;

    if(!oled_task_user()) {
        done_once = false;
        return false;
    }

    if (!done_once){
        render_logo();
        oled_set_cursor(7, oled_max_lines()-1);
        oled_write("Layer: ", false);
        oled_write(depad_str(get_u16_str(get_highest_layer(layer_state), ' '), ' '), false);
        done_once = true;
    } else {
        if (current_layer != get_highest_layer(layer_state)) {
            current_layer = get_highest_layer(layer_state);
            oled_set_cursor(7+6, oled_max_lines()-1);
            oled_write(depad_str(get_u16_str(current_layer, ' '), ' '), false);
        }
    }

    return false;
}
